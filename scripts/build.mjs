// Generates the Codex agent roles from the Claude Code agent files.
//
//   node scripts/build.mjs           write plugins/aidrian/codex/agents/*.toml
//   node scripts/build.mjs --check   exit 1 if those files are missing, stale, or extra
//
// Claude Code reads plugins/aidrian/agents/*.md directly. Codex cannot load agents from a plugin,
// so each agent becomes a standalone TOML role that plugins/aidrian/codex/install-agents.mjs copies
// into ~/.codex/agents/. Skills need no build: both hosts read the same SKILL.md files.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const AGENTS = path.join(ROOT, 'plugins/aidrian/agents');
export const CODEX_AGENTS = path.join(ROOT, 'plugins/aidrian/codex/agents');
export const PREFIX = 'aidrian-';

// Codex has no `max`; its highest level is `xhigh`.
const EFFORT = { low: 'low', medium: 'medium', high: 'high', xhigh: 'xhigh', max: 'xhigh' };

export function readAgents() {
  return readdirSync(AGENTS)
    .filter((file) => file.endsWith('.md'))
    .sort()
    .map((file) => {
      const text = readFileSync(path.join(AGENTS, file), 'utf8');
      const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
      if (!match) throw new Error(`${file}: missing frontmatter`);
      return { file, meta: parse(match[1]), body: match[2].trim() };
    });
}

// The files Codex should have, keyed by file name.
export function renderCodexAgents(agents = readAgents()) {
  return new Map(agents.map((agent) => [`${PREFIX}${agent.meta.name}.toml`, renderAgent(agent)]));
}

function renderAgent({ file, meta, body }) {
  const effort = EFFORT[meta.effort];
  if (!effort) throw new Error(`${file}: unknown effort ${JSON.stringify(meta.effort)}`);
  return [
    `# Generated by scripts/build.mjs from plugins/aidrian/agents/${file}. Do not edit.`,
    `# The Claude Code agent pins model "${meta.model}"; this role inherits the Codex session's model.`,
    `name = ${basicString(PREFIX + meta.name)}`,
    `description = ${basicString(meta.description)}`,
    `model_reasoning_effort = "${effort}"`,
    `developer_instructions = """`,
    multilineBody(`${codexPreamble(meta)}\n\n${body}`),
    `"""`,
    '',
  ].join('\n');
}

function codexPreamble(meta) {
  const denied = toList(meta.disallowedTools);
  const allowed = meta.tools === undefined ? null : toList(meta.tools);
  const canEdit = !denied.includes('Write') && !denied.includes('Edit') && (!allowed || allowed.includes('Write') || allowed.includes('Edit'));
  const canShell = !denied.includes('Bash') && (!allowed || allowed.includes('Bash'));
  const lines = [
    'This role comes from the aidrian plugin and was written for Claude Code. On Codex:',
    `- Other agents named below are installed as \`${PREFIX}<name>\` Codex agents; spawn them by that name.`,
    '- `Agent` or `subagent_type` means spawn that Codex agent, `SendMessage` means follow up with it, and the `Skill` tool means load the named skill.',
    '- Claude tool names such as `Read`, `Grep`, `Glob`, `Edit`, `Write`, and `Bash` mean your equivalent file and shell tools.',
  ];
  if (!canEdit && !canShell) lines.push('- You are read-only: do not create or edit files, and run only commands that change nothing.');
  else if (!canEdit) lines.push('- Do not create or edit files directly; change the repository only through the commands these instructions allow.');
  return lines.join('\n');
}

function toList(value) {
  if (value === undefined) return [];
  return Array.isArray(value) ? value : String(value).split(',').map((item) => item.trim());
}

function basicString(value) {
  return JSON.stringify(String(value).replace(/\s+/g, ' ').trim());
}

// Body of a TOML multi-line basic string: escape backslashes and any run of three quotes.
function multilineBody(text) {
  if (/[\u0000-\u0008\u000b-\u001f\u007f]/.test(text)) throw new Error('agent text contains a control character');
  return text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"');
}

export function compareCodexAgents(expected = renderCodexAgents()) {
  const actual = existsSync(CODEX_AGENTS) ? readdirSync(CODEX_AGENTS).filter((file) => file.endsWith('.toml')) : [];
  const problems = [];
  for (const [file, text] of expected) {
    if (!actual.includes(file)) problems.push(`missing ${file}`);
    else if (readFileSync(path.join(CODEX_AGENTS, file), 'utf8') !== text) problems.push(`stale ${file}`);
  }
  for (const file of actual) if (!expected.has(file)) problems.push(`extra ${file}`);
  return problems;
}

function main(args) {
  const expected = renderCodexAgents();
  if (args.includes('--check')) {
    const problems = compareCodexAgents(expected);
    if (problems.length) {
      console.error(`Codex agents are out of date (run npm run build):\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`ok: ${expected.size} Codex agents are current`);
    return;
  }
  rmSync(CODEX_AGENTS, { recursive: true, force: true });
  mkdirSync(CODEX_AGENTS, { recursive: true });
  for (const [file, text] of expected) writeFileSync(path.join(CODEX_AGENTS, file), text);
  console.log(`wrote ${expected.size} Codex agents to ${path.relative(ROOT, CODEX_AGENTS)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
