// scripts/build.mjs: the neutral agent sources, the provider files, how they merge, and the generated Claude Code agents.

import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { parse } from 'yaml';

import { CLAUDE_AGENTS, NEUTRAL, agentSettings, compareGenerated, providerNames, readAgents, readProviders, renderAgents } from '../scripts/build.mjs';

// A scratch plugin: agents-src/, providers/, agent-addons/, and a knowledge skill.
function scratch(t, { sources = { lead: LEAD }, claude = {}, codex = {} } = {}) {
  const dir = mkdtempSync(path.join(tmpdir(), 'aidrian-build-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const dirs = {
    sourcesDir: path.join(dir, 'agents-src'),
    providersDir: path.join(dir, 'providers'),
    addonsDir: path.join(dir, 'agent-addons'),
    skillsDir: path.join(dir, 'skills'),
  };
  for (const sub of Object.values(dirs)) mkdirSync(sub);
  mkdirSync(path.join(dirs.skillsDir, 'knowledge'));
  writeFileSync(path.join(dirs.skillsDir, 'knowledge/SKILL.md'), '---\nname: knowledge\n---\n');
  for (const [name, text] of Object.entries(sources)) writeFileSync(path.join(dirs.sourcesDir, `${name}.md`), text);
  writeFileSync(path.join(dirs.providersDir, 'claude.json'), JSON.stringify(claude));
  writeFileSync(path.join(dirs.providersDir, 'codex.json'), JSON.stringify(codex));
  const agents = () => readAgents(dirs);
  return { ...dirs, agents, providers: () => readProviders({ providersDir: dirs.providersDir, agents: agents() }) };
}

const source = (fields, body = 'Lead the work.') => `---\n${fields}\n---\n\n${body}\n`;
const LEAD = source('name: lead\ndescription: Leads the test work.\naccess: write\nskills: [knowledge]');

test('the generated Claude Code agents are current (npm run build regenerates them)', () => {
  assert.deepEqual(compareGenerated('claude'), []);
});

test('--check reports a hand-edited, missing, or extra generated file', () => {
  const expected = renderAgents('claude');
  const [file, text] = expected.entries().next().value;
  const edited = new Map(expected).set(file, `${text}hand edit\n`);
  assert.deepEqual(compareGenerated('claude', edited), [`stale plugins/aidrian/agents/${file}`]);
  const missing = new Map(expected).set('ghost.md', 'x');
  assert.deepEqual(compareGenerated('claude', missing), ['missing plugins/aidrian/agents/ghost.md']);
  const fewer = new Map(expected);
  fewer.delete(file);
  assert.deepEqual(compareGenerated('claude', fewer), [`extra plugins/aidrian/agents/${file}`]);
});

test('every generated Claude Code agent says it is generated, and carries its source body unchanged', () => {
  for (const { file, body } of readAgents()) {
    const text = readFileSync(path.join(CLAUDE_AGENTS, file), 'utf8');
    assert.ok(text.startsWith(`---\n# Generated by scripts/build.mjs from plugins/aidrian/agents-src/${file} and providers/claude.json. Do not edit.\n`), file);
    assert.ok(text.endsWith(`\n---\n\n${body}\n`), file);
  }
});

test('a neutral source fails on a field outside the neutral set', (t) => {
  assert.deepEqual(NEUTRAL, ['name', 'description', 'access', 'skills']);
  for (const field of ['model: opus', 'effort: high', 'disallowedTools: [Bash]', 'color: blue', 'tools: Read']) {
    const { agents } = scratch(t, { sources: { lead: source(`name: lead\ndescription: Leads.\naccess: write\n${field}`) } });
    assert.throws(agents, new RegExp(`"${field.split(':')[0]}" is not a neutral field`), field);
  }
});

test('a neutral source fails on a wrong name, a missing description, an unknown access, or an unknown skill', (t) => {
  const cases = [
    ['name: other\ndescription: Leads.\naccess: write', /name must be "lead"/],
    ['name: lead\naccess: write', /no description/],
    ['name: lead\ndescription: Leads.\naccess: none', /access must be read-only or write/],
    ['name: lead\ndescription: Leads.', /access must be read-only or write/],
    ['name: lead\ndescription: Leads.\naccess: write\nskills: [nowhere]', /no skill "nowhere"/],
    ['name: lead\ndescription: Leads.\naccess: write\nskills: knowledge', /skills must be a list/],
  ];
  for (const [fields, message] of cases) assert.throws(scratch(t, { sources: { lead: source(fields) } }).agents, message, fields);
});

test('a neutral source fails on a provider model or tool name', (t) => {
  assert.deepEqual(providerNames('Reviews with opus'), ['opus']);
  assert.deepEqual(providerNames('Runs on claude-opus-5-5 or gpt-5.5'), ['claude-opus-5-5']);
  assert.deepEqual(providerNames('Uses Bash and mcp__github__get_commit'), ['Bash']);
  assert.deepEqual(providerNames('Calls the `Write` tool'), ['Write']);
  assert.deepEqual(providerNames(['knowledge', 'Agent']), ['Agent']);
  assert.deepEqual(providerNames('Read-only code review. Write or revise a plan with an Agent of change.'), []);

  const cases = [
    ['description: Plans with Fable.', /description names Fable/],
    ['description: Edits through NotebookEdit.', /description names NotebookEdit/],
    ['description: Leads.\nskills: [Skill]', /skills names Skill/],
  ];
  for (const [fields, message] of cases) {
    const { agents } = scratch(t, { sources: { lead: source(`name: lead\naccess: write\n${fields}`) } });
    assert.throws(agents, message, fields);
  }
  // The shipped sources hold none: readAgents would have thrown.
  for (const { meta } of readAgents()) for (const key of NEUTRAL) assert.deepEqual(providerNames(meta[key]), [], `${meta.name}: ${key}`);
});

test('a provider entry fails for an unknown agent, a field the provider does not support, or a field the source owns', (t) => {
  const cases = [
    [{ claude: { ghost: { model: 'opus' } } }, /providers\/claude\.json: "ghost" is not an agent in agents-src/],
    [{ codex: { ghost: {} } }, /providers\/codex\.json: "ghost" is not an agent/],
    [{ claude: { lead: { hooks: {} } } }, /"lead" sets hooks, which is not a claude field this build supports/],
    [{ claude: { lead: { permissionMode: 'plan' } } }, /sets permissionMode, which is not a claude field/],
    [{ claude: { '*': { model_reasoning_effort: 'high' } } }, /"\*" sets model_reasoning_effort, which is not a claude field/],
    [{ codex: { lead: { effort: 'high' } } }, /"lead" sets effort, which is not a codex field this build supports/],
    [{ codex: { lead: { sandbox_mode: 'read-only' } } }, /sets sandbox_mode, which is not a codex field/],
    [{ claude: { lead: { description: 'Other.' } } }, /"lead" sets description, which the build writes from agents-src/],
    [{ claude: { lead: { skills: ['x'] } } }, /sets skills, which the build writes from agents-src/],
    [{ codex: { lead: { developer_instructions: 'x' } } }, /sets developer_instructions, which the build writes/],
    [{ claude: { lead: 'opus' } }, /"lead" must be an object of claude fields/],
  ];
  for (const [files, message] of cases) assert.throws(scratch(t, files).providers, message, JSON.stringify(files));
});

test('a provider file needs a generator, and every generator needs its provider file', (t) => {
  const extra = scratch(t);
  writeFileSync(path.join(extra.providersDir, 'opencode.json'), '{}');
  assert.throws(extra.providers, /providers\/opencode\.json: no opencode generator in scripts\/build\.mjs/);

  const missing = scratch(t);
  rmSync(path.join(missing.providersDir, 'codex.json'));
  assert.throws(missing.providers, /providers\/codex\.json is missing/);
});

test('settings merge one field at a time: "*" defaults, then the access shortcut, then the agent entry', (t) => {
  const reader = source('name: reader\ndescription: Reads.\naccess: read-only');
  const { agents, providers } = scratch(t, {
    sources: { lead: LEAD, reader },
    claude: { '*': { model: 'sonnet', effort: 'medium', disallowedTools: ['Agent'] }, lead: { model: 'opus' }, reader: { disallowedTools: ['Write', 'Edit', 'NotebookEdit', 'Bash'] } },
    codex: { '*': { model_reasoning_effort: 'medium' }, reader: { model_reasoning_effort: 'low' } },
  });
  const [lead, read] = agents();
  const { claude, codex } = providers();
  assert.deepEqual(agentSettings('claude', lead, claude), { model: 'opus', effort: 'medium', disallowedTools: ['Agent'] });
  assert.deepEqual(agentSettings('claude', read, claude), { model: 'sonnet', effort: 'medium', disallowedTools: ['Write', 'Edit', 'NotebookEdit', 'Bash'] });
  assert.deepEqual(agentSettings('codex', read, codex), { model_reasoning_effort: 'low' });

  // Without an entry, the shortcut wins over the "*" defaults.
  const bare = scratch(t, { sources: { reader }, claude: { '*': { disallowedTools: ['Agent'] } } });
  const [onlyReader] = bare.agents();
  assert.deepEqual(agentSettings('claude', onlyReader, bare.providers().claude), { disallowedTools: ['Write', 'Edit', 'NotebookEdit'] });
});

test('a Claude Code entry may not undo its agent\'s access', (t) => {
  const reader = source('name: reader\ndescription: Reads.\naccess: read-only');
  const cases = [
    [{ reader }, { reader: { disallowedTools: ['Bash'] } }, /reader .*access is read-only, but its tools still include Write, Edit, NotebookEdit/],
    [{ reader }, { reader: { tools: ['Read', 'Edit'], disallowedTools: [] } }, /access is read-only, but its tools still include Edit/],
    [{ lead: LEAD }, { lead: { disallowedTools: ['Write', 'Edit'] } }, /access is write, but its tools include neither Write nor Edit/],
  ];
  for (const [sources, claude, message] of cases) {
    const { agents, providers } = scratch(t, { sources, claude });
    assert.throws(() => renderAgents('claude', agents(), providers().claude), message);
  }
  // An allowlist without the file tools is read-only too.
  const allow = scratch(t, { sources: { reader }, claude: { reader: { tools: 'Read, Grep', disallowedTools: [] } } });
  assert.doesNotThrow(() => renderAgents('claude', allow.agents(), allow.providers().claude));
});

test('the Claude Code agent has the neutral fields, the provider fields in a fixed order, and plugin-named skills', (t) => {
  const { agents, providers } = scratch(t, {
    sources: { lead: source('name: lead\ndescription: "Leads: the test work, #1."\naccess: write\nskills: [knowledge]') },
    claude: { lead: { maxTurns: 5, color: 'blue', model: 'opus', experimental: { cacheTtl: '1h' } } },
  });
  const text = renderAgents('claude', agents(), providers().claude).get('lead.md');
  const [, frontmatter, body] = /^---\n([\s\S]*?)\n---\n\n([\s\S]*)$/.exec(text);
  assert.equal(body, 'Lead the work.\n');
  assert.deepEqual(frontmatter.split('\n').slice(1).map((line) => line.split(':')[0]), ['name', 'description', 'model', 'color', 'maxTurns', 'experimental', 'skills']);
  assert.deepEqual(parse(frontmatter), {
    name: 'lead',
    description: 'Leads: the test work, #1.',
    model: 'opus',
    color: 'blue',
    maxTurns: 5,
    experimental: { cacheTtl: '1h' },
    skills: ['aidrian:knowledge'],
  });
});

test('build reads <agent>.<provider>.md add-ons into that provider\'s agent, and fails on any other add-on name', (t) => {
  const { addonsDir, agents, providers } = scratch(t);
  assert.deepEqual(agents().map(({ addons }) => addons), [{}]);
  writeFileSync(path.join(addonsDir, 'lead.codex.md'), '\nOn Codex only.\n');
  writeFileSync(path.join(addonsDir, 'lead.claude.md'), 'On Claude Code only.\n');
  assert.deepEqual(agents().map(({ addons }) => addons), [{ claude: 'On Claude Code only.', codex: 'On Codex only.' }]);
  const claude = renderAgents('claude', agents(), providers().claude).get('lead.md');
  assert.ok(claude.endsWith('\n---\n\nLead the work.\n\nOn Claude Code only.\n'));
  assert.doesNotMatch(claude, /On Codex only/);
  const codex = renderAgents('codex', agents(), providers().codex).get('aidrian-lead.toml');
  assert.match(codex, /Lead the work\.\n\nOn Codex only\.\n"""/);
  assert.doesNotMatch(codex, /On Claude Code only/);

  const cases = [
    ['lead.opencode.md', /lead\.opencode\.md: no opencode agents are generated; the providers are claude, codex/],
    ['lead.cursor.md', /lead\.cursor\.md: no cursor agents are generated/],
    ['ghost.codex.md', /ghost\.codex\.md: name it <agent>\.<provider>\.md after an agent in agents-src/],
    ['notes.md', /notes\.md: name it <agent>\.<provider>\.md/],
  ];
  for (const [file, message] of cases) {
    writeFileSync(path.join(addonsDir, file), 'text\n');
    assert.throws(agents, message, file);
    rmSync(path.join(addonsDir, file));
  }
});
