// Generates the Codex agent roles from the Claude Code agent files.
//
//   node scripts/build.mjs           write plugins/aidrian/codex/agents/*.toml
//   node scripts/build.mjs --check   exit 1 if those files are missing, stale, or extra
//
// Claude Code reads plugins/aidrian/agents/*.md directly. Codex cannot load agents from a plugin,
// so each agent becomes a standalone TOML role that plugins/aidrian/codex/install-agents.mjs copies
// into ~/.codex/agents/. Skills need no build: both hosts read the same SKILL.md files.
//
// An agent is written for every host. Text only Codex needs goes in plugins/aidrian/agent-addons/<name>.codex.md,
// which the Codex role gets after the agent's body. The add-ons cannot sit in agents/: Claude Code loads every .md there
// as an agent. Claude Code reads agents/<name>.md as it is, so nothing could append a <name>.claude.md, and no OpenCode
// role is generated yet: both names fail the build rather than be silently ignored.

import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';

const ROOT = path.resolve(import.meta.dirname, '..');
const AGENTS = path.join(ROOT, 'plugins/aidrian/agents');
const ADDONS = path.join(ROOT, 'plugins/aidrian/agent-addons');
export const CODEX_AGENTS = path.join(ROOT, 'plugins/aidrian/codex/agents');
export const PREFIX = 'aidrian-';

// Codex has no `max`; its highest level is `xhigh`.
const EFFORT = { low: 'low', medium: 'medium', high: 'high', xhigh: 'xhigh', max: 'xhigh' };

// Each agent with its host add-ons: { file, meta, body, addons: { codex } }.
export function readAgents({ agentsDir = AGENTS, addonsDir = ADDONS } = {}) {
  const agents = readdirSync(agentsDir)
    .filter((file) => file.endsWith('.md'))
    .sort()
    .map((file) => {
      const text = readFileSync(path.join(agentsDir, file), 'utf8');
      const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text);
      if (!match) throw new Error(`${file}: missing frontmatter`);
      return { file, meta: parse(match[1]), body: match[2].trim(), addons: {} };
    });
  const byName = new Map(agents.map((agent) => [agent.file.replace(/\.md$/, ''), agent]));
  for (const file of existsSync(addonsDir) ? readdirSync(addonsDir).sort() : []) {
    const [, name, host] = /^(.+)\.([a-z]+)\.md$/.exec(file) ?? [];
    const where = `agent-addons/${file}`;
    if (!byName.has(name)) throw new Error(`${where}: name it <agent>.codex.md after an agent in agents/`);
    if (host === 'claude') throw new Error(`${where}: Claude Code reads agents/${name}.md as it is; put the text there`);
    if (host === 'opencode') throw new Error(`${where}: no OpenCode role is generated yet`);
    if (host !== 'codex') throw new Error(`${where}: name it <agent>.codex.md after an agent in agents/`);
    byName.get(name).addons.codex = readFileSync(path.join(addonsDir, file), 'utf8').trim();
  }
  return agents;
}

// The files Codex should have, keyed by file name.
export function renderCodexAgents(agents = readAgents()) {
  const names = agents.map((agent) => agent.meta.name);
  return new Map(agents.map((agent) => [`${PREFIX}${agent.meta.name}.toml`, renderAgent(agent, names)]));
}

function renderAgent({ file, meta, body, addons = {} }, pluginAgents) {
  const effort = EFFORT[meta.effort];
  if (!effort) throw new Error(`${file}: unknown effort ${JSON.stringify(meta.effort)}`);
  const text = addons.codex ? `${body}\n\n${addons.codex}` : body;
  return [
    `# Generated by scripts/build.mjs from plugins/aidrian/agents/${file}. Do not edit.`,
    `# The Claude Code agent pins model "${meta.model}"; this role inherits the Codex session's model.`,
    `name = ${basicString(PREFIX + meta.name)}`,
    `description = ${basicString(meta.description)}`,
    `model_reasoning_effort = "${effort}"`,
    `developer_instructions = """`,
    multilineBody(`${codexPreamble(meta, text, pluginAgents)}\n\n${text}`),
    `"""`,
    '',
  ].join('\n');
}

function codexPreamble(meta, body, pluginAgents) {
  const denied = toList(meta.disallowedTools);
  const allowed = meta.tools === undefined ? null : toList(meta.tools);
  const canEdit = !denied.includes('Write') && !denied.includes('Edit') && (!allowed || allowed.includes('Write') || allowed.includes('Edit'));
  const canShell = !denied.includes('Bash') && (!allowed || allowed.includes('Bash'));
  const lines = ['This role comes from the aidrian plugin and was written for Claude Code. On Codex:'];
  // Only this plugin's agents carry the prefix. A project's own roles, such as `architect`, keep their names.
  const named = pluginAgents.filter((name) => name !== meta.name && namesAgent(body, name));
  if (named.length) {
    const renames = named.map((name) => `\`${name}\` is \`${PREFIX}${name}\``).join(', ');
    lines.push(`- This plugin's agents named below have Codex names: ${renames}. Spawn them by those names; any other agent named below is the project's own.`);
  }
  lines.push(
    '- `Agent` or `subagent_type` means spawn that Codex agent, `SendMessage` means follow up with it, and the `Skill` tool means load the named skill.',
    '- Claude tool names such as `Read`, `Grep`, `Glob`, `Edit`, `Write`, and `Bash` mean your equivalent file and shell tools.',
  );
  if (!canEdit && !canShell) lines.push('- You are read-only: do not create or edit files, and run only commands that change nothing.');
  else if (!canEdit) lines.push('- Do not create or edit files directly; change the repository only through the commands these instructions allow.');
  return lines.join('\n');
}

// Some agents share a name with a skill. "The `agent-issue-writer` skill" or "the skill `agent-issue-writer`" names
// the skill, which keeps its name on Codex; any other backticked use of the name is the agent.
function namesAgent(body, name) {
  return new RegExp(`(?<!skill )\`${name}\`(?! skill\\b)`).test(body);
}

function toList(value) {
  if (value === undefined) return [];
  return Array.isArray(value) ? value : String(value).split(',').map((item) => item.trim());
}

function basicString(value) {
  return JSON.stringify(String(value).replace(/\s+/g, ' ').trim());
}

// Body of a TOML multi-line basic string: escape backslashes and any run of three quotes.
function multilineBody(text) {
  if (/[\u0000-\u0008\u000b-\u001f\u007f]/.test(text)) throw new Error('agent text contains a control character');
  return text.replace(/\\/g, '\\\\').replace(/"""/g, '""\\"');
}

export function compareCodexAgents(expected = renderCodexAgents()) {
  const actual = existsSync(CODEX_AGENTS) ? readdirSync(CODEX_AGENTS).filter((file) => file.endsWith('.toml')) : [];
  const problems = [];
  for (const [file, text] of expected) {
    if (!actual.includes(file)) problems.push(`missing ${file}`);
    else if (readFileSync(path.join(CODEX_AGENTS, file), 'utf8') !== text) problems.push(`stale ${file}`);
  }
  for (const file of actual) if (!expected.has(file)) problems.push(`extra ${file}`);
  return problems;
}

function main(args) {
  // Any other argument fails: a mistyped --check must not fall through to regenerating the files.
  const unknown = args.find((arg) => arg !== '--check');
  if (unknown !== undefined) {
    console.error(`usage: node scripts/build.mjs [--check]\nunknown argument: ${unknown}`);
    process.exit(1);
  }
  const expected = renderCodexAgents();
  if (args.includes('--check')) {
    const problems = compareCodexAgents(expected);
    if (problems.length) {
      console.error(`Codex agents are out of date (run npm run build):\n  ${problems.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`ok: ${expected.size} Codex agents are current`);
    return;
  }
  rmSync(CODEX_AGENTS, { recursive: true, force: true });
  mkdirSync(CODEX_AGENTS, { recursive: true });
  for (const [file, text] of expected) writeFileSync(path.join(CODEX_AGENTS, file), text);
  console.log(`wrote ${expected.size} Codex agents to ${path.relative(ROOT, CODEX_AGENTS)}`);
}

// Run only as the entry script. process.argv[1] is unset under `node -e` and need not be a file under `node -p`.
// import.meta.url has symlinks resolved, so resolve the entry path too, or a symlinked --check passes having checked nothing.
const entry = process.argv[1];
if (entry && existsSync(entry) && import.meta.url === pathToFileURL(realpathSync(entry)).href) main(process.argv.slice(2));
