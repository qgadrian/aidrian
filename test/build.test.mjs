// A scratch hooks.json holding one group under each event given, as { <event>: [group, ...] }.
function scratchHooks(t, hooks) {
  const dir = mkdtempSync(path.join(tmpdir(), 'aidrian-hooks-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'hooks.json');
  writeFileSync(file, JSON.stringify({ hooks }));
  return file;
}
// A hooks.json hook; timeout null leaves the field out.
const hook = (command, timeout = 5) => ({ type: 'command', command, ...(timeout === null ? {} : { timeout }) });
const NODE = (name) => `node "$CLAUDE_PLUGIN_ROOT/scripts/${name}.mjs"`;

test('the committed OpenCode route list is the one hooks.json generates (npm run build regenerates it)', () => {
  assert.equal(readFileSync(OPENCODE_ROUTES, 'utf8'), renderRoutes());
  assert.deepEqual(compareRoutes(), []);
  const hooks = JSON.parse(readFileSync(HOOKS_FILE, 'utf8')).hooks;
  const count = Object.values(hooks).flat().reduce((sum, group) => sum + group.hooks.length, 0);
  assert.equal(JSON.parse(renderRoutes()).length, count, 'every hooks.json hook is a route');
});

test('--check reports a stale or missing OpenCode route list', (t) => {
  const dir = mkdtempSync(path.join(tmpdir(), 'aidrian-routes-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'routes.generated.json');
  assert.match(compareRoutes(renderRoutes(), file)[0], /^missing .*routes\.generated\.json$/);
  writeFileSync(file, renderRoutes().replace('5000', '6000'));
  assert.match(compareRoutes(renderRoutes(), file)[0], /^stale .*routes\.generated\.json$/);
  writeFileSync(file, renderRoutes());
  assert.deepEqual(compareRoutes(renderRoutes(), file), []);
});

test('a route keeps hooks.json order, its script, its flags, and its timeout in whole milliseconds', (t) => {
  const file = scratchHooks(t, {
    SessionStart: [{ hooks: [hook(NODE('hook-a')), hook(`${NODE('hook-a')} --subagent --dry-run`, 15)] }],
    PreToolUse: [{ matcher: '*', hooks: [hook(NODE('hook-b'), 0.5)] }, { matcher: 'Edit|Write', hooks: [hook(NODE('hook-c'), 16.1)] }],
  });
  const text = renderRoutes(file);
  assert.ok(text.endsWith(']\n') && text.startsWith('[\n  {\n    "event"'), 'two-space JSON with a trailing newline');
  assert.deepEqual(JSON.parse(text), [
    { event: 'SessionStart', matcher: null, script: 'hook-a.mjs', args: [], timeoutMs: 5000 },
    { event: 'SessionStart', matcher: null, script: 'hook-a.mjs', args: ['--subagent', '--dry-run'], timeoutMs: 15000 },
    { event: 'PreToolUse', matcher: '*', script: 'hook-b.mjs', args: [], timeoutMs: 500 },
    { event: 'PreToolUse', matcher: '^(?:Edit|Write)$', script: 'hook-c.mjs', args: [], timeoutMs: 16100 },
  ]);
  assert.equal(renderRoutes(file), text, 'deterministic');
});

test('a route matcher is null with no matcher, "*" for any tool, a list of names anchored, and a pattern as it is', () => {
  assert.equal(routeMatcher(undefined), null);
  assert.equal(routeMatcher('*'), '*');
  assert.equal(routeMatcher('Edit|Write'), '^(?:Edit|Write)$');
  assert.equal(routeMatcher('code-reviewer'), '^(?:code-reviewer)$');
  assert.equal(routeMatcher('mcp__.*'), 'mcp__.*');
  assert.equal(routeMatcher('^Notebook'), '^Notebook');
  assert.throws(() => routeMatcher(''), /is not a pattern; use "\*" for every tool/);
  assert.throws(() => routeMatcher('mcp__(unclosed'), SyntaxError);
  assert.throws(() => routeMatcher('Edit)|(.*'), SyntaxError);
});

test('a tool event group with no matcher fails the route build, naming its event, as Claude Code runs it on every tool', (t) => {
  for (const event of ['PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest', 'PermissionDenied']) {
    for (const group of [{ hooks: [hook(NODE('hook-x'))] }, { matcher: null, hooks: [hook(NODE('hook-x'))] }]) {
      const file = scratchHooks(t, { [event]: [group] });
      assert.throws(() => renderRoutes(file), new RegExp(`^Error: .*: ${event}: a group with no matcher .*say "\\*" to mean every tool$`), event);
    }
    const all = scratchHooks(t, { [event]: [{ matcher: '*', hooks: [hook(NODE('hook-x'))] }] });
    assert.equal(JSON.parse(renderRoutes(all))[0].matcher, '*', `${event} "*"`);
  }
  for (const event of ['SessionStart', 'SubagentStart', 'UserPromptSubmit', 'PreCompact', 'Stop', 'SubagentStop', 'SessionEnd']) {
    const file = scratchHooks(t, { [event]: [{ hooks: [hook(NODE('hook-x'))] }] });
    assert.equal(JSON.parse(renderRoutes(file))[0].matcher, null, event);
  }
});

test('a matcher with a comma or whitespace fails the route build, as a host may read it as a list of names', (t) => {
  for (const matcher of ['Edit, Write', 'Edit,Write', 'Edit Write', 'Edit|Write ', 'Edit\t|Write', 'mcp__.{1,3}']) {
    assert.throws(() => routeMatcher(matcher), /holds a comma or whitespace, which a host may read as a list; separate names with "\|"/, matcher);
    const file = scratchHooks(t, { PostToolUse: [{ matcher, hooks: [hook(NODE('hook-x'))] }] });
    assert.throws(() => renderRoutes(file), /PostToolUse: matcher .* holds a comma or whitespace/, matcher);
  }
});

// Whether a hooks.json matcher fires on the tool `name` as Claude Code reads it (code.claude.com/docs/en/hooks): "*", empty,
// or none on every tool; only letters, digits, _, -, spaces, commas, and | a list of exact names split on | or ,; any
// other a regular expression that may match anywhere in the name.
const claudeFires = (matcher, name) => {
  if (matcher === undefined || matcher === '' || matcher === '*') return true;
  if (/^[A-Za-z0-9_ ,|-]+$/u.test(matcher)) return matcher.split(/\s*[|,]\s*/u).includes(name);
  return new RegExp(matcher, 'u').test(name);
};
// The scripts the routes built from `hooks` run on the tool `name`, through the bridge's own selector.
const routedScripts = (t, hooks, name) => {
  const events = Object.fromEntries(Object.keys(hooks).map((event) => [event, 'tool.hook']));
  return selectRoutes(JSON.parse(renderRoutes(scratchHooks(t, hooks))), events, 'tool.hook', name).map((route) => route.script);
};

test('a route fires where Claude Code fires its hook: a pattern anywhere in the name, a list of names on those alone', (t) => {
  const hooks = { PostToolUse: [
    { matcher: 'ash.*', hooks: [hook(NODE('hook-pattern'))] },
    { matcher: 'Edit|Write', hooks: [hook(NODE('hook-list'))] },
  ] };
  assert.deepEqual(routedScripts(t, hooks, 'Bash'), ['hook-pattern.mjs']);
  assert.deepEqual(routedScripts(t, hooks, 'NotebookEdit'), []);
  assert.deepEqual(routedScripts(t, hooks, 'Edit'), ['hook-list.mjs']);
  assert.equal(claudeFires('ash.*', 'Bash'), true);
  assert.equal(claudeFires('Edit|Write', 'NotebookEdit'), false);
});

test('each hooks.json tool matcher, as a route, fires on the names Claude Code fires its hook on', (t) => {
  const hooks = JSON.parse(readFileSync(HOOKS_FILE, 'utf8')).hooks;
  const matchers = ['PreToolUse', 'PostToolUse', 'PostToolUseFailure', 'PermissionRequest', 'PermissionDenied']
    .flatMap((event) => (hooks[event] ?? []).map((group) => group.matcher));
  const listed = matchers.filter((matcher) => /^[A-Za-z0-9_|-]+$/u.test(matcher)).flatMap((matcher) => matcher.split('|'));
  const names = [...new Set([...STANDARD_NAMES, ...listed, 'mcp__linear__save_issue', 'mcp__plugin_github_github__merge_pull_request', 'xmcp__a__b'])];
  assert.ok(names.includes('NotebookEdit') && names.includes('Bash'));
  const groups = matchers.map((matcher, index) => ({ matcher, hooks: [hook(NODE(`hook-${index}`))] }));
  const routes = JSON.parse(renderRoutes(scratchHooks(t, { PostToolUse: groups })));
  for (const name of names) {
    const routed = selectRoutes(routes, { PostToolUse: 'tool.hook' }, 'tool.hook', name).map((route) => route.script);
    const expected = matchers.flatMap((matcher, index) => (claudeFires(matcher, name) ? [`hook-${index}.mjs`] : []));
    assert.deepEqual(routed, expected, name);
  }
});

test('a handler or group field the bridge cannot honour fails the route build, naming the field, its event, and command', (t) => {
  for (const extra of [{ if: 'Bash(git *)' }, { async: true }, { statusMessage: 'Checking' }]) {
    const [field] = Object.keys(extra);
    const file = scratchHooks(t, { PostToolUse: [{ matcher: 'Bash', hooks: [{ ...hook(NODE('hook-x')), ...extra }] }] });
    const named = `PostToolUse hook ${JSON.stringify(NODE('hook-x'))}: field "${field}" is one the OpenCode bridge cannot honour`;
    assert.throws(() => renderRoutes(file), (error) => error.message.endsWith(named), field);
  }
  const group = scratchHooks(t, { Stop: [{ hooks: [hook(NODE('hook-stop'))], description: 'stop' }] });
  const named = `Stop group of ${JSON.stringify(NODE('hook-stop'))}: field "description" is one the OpenCode bridge cannot honour`;
  assert.throws(() => renderRoutes(group), (error) => error.message.endsWith(named));
});

test('a hooks.json command the bridge cannot run without a shell fails the route build, naming its event and command', (t) => {
  const refused = [
    ['bash -c "node x.mjs"', /runs only node/],
    [`${NODE('hook-x')} && rm -rf /`, /runs only node/],
    ['node "$HOME/x.mjs"', /runs only node/],
    [`${NODE('hook-x')} payload`, /runs only node/],
    [`${NODE('hook-x')} --flag=$VALUE`, /runs only node/],
    [`${NODE('hook-x')}  --flag`, /runs only node/],
    ['node "$CLAUDE_PLUGIN_ROOT/scripts/../lib/x.mjs"', /runs only node/],
    ['node "$CLAUDE_PLUGIN_ROOT/scripts/Hook_X.mjs"', /runs only node/],
    ["node '$CLAUDE_PLUGIN_ROOT/scripts/hook-x.mjs'", /runs only node/],
    [`${NODE('hook-x')}\n`, /runs only node/],
    [`${NODE('hook-x')}\nrm -rf /`, /runs only node/],
    [`${NODE('hook-x')} `, /runs only node/],
    [`${NODE('hook-x')}\t--flag`, /runs only node/],
    [`${NODE('hook-x')} --a" "--b`, /runs only node/],
    [NODE('hook-\u0445'), /runs only node/], // a Cyrillic х, a lookalike of x
  ];
  for (const [command, why] of refused) {
    const file = scratchHooks(t, { PostToolUse: [{ matcher: 'Bash', hooks: [hook(command)] }] });
    assert.throws(() => renderRoutes(file), (error) => why.test(error.message) && error.message.includes(`PostToolUse hook ${JSON.stringify(command)}`), command);
  }
  for (const timeout of [null, 0, -5, '5', 1e308, 1e-9, 2 ** 31]) {
    const file = scratchHooks(t, { Stop: [{ hooks: [hook(NODE('hook-stop'), timeout)] }] });
    assert.throws(() => renderRoutes(file), /Stop hook .*hook-stop\.mjs.*: timeout must be a positive number/, String(timeout));
  }
  const prompt = scratchHooks(t, { Stop: [{ hooks: [{ type: 'prompt', command: NODE('hook-stop'), timeout: 5 }] }] });
  assert.throws(() => renderRoutes(prompt), /Stop hook .*: type must be "command"/);
  const badMatcher = scratchHooks(t, { PreToolUse: [{ matcher: 'mcp__(', hooks: [hook(NODE('hook-x'))] }] });
  assert.throws(() => renderRoutes(badMatcher), /PreToolUse: Invalid regular expression/);
});
